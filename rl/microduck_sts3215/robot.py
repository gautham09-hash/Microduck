"""The STS3215 Microduck as an Isaac Lab articulation.

The model is sim/sts3215/robot_walk.xml (generated by cad/sts3215/build_mjcf.py: a gearbox-play hinge behind each
servo, soles and thigh/trunk collisions, no MuJoCo actuators), converted to USD by rl/convert_usd.py.

Each servo is Rhoban BAM's identified STS3215 model (cad/sts3215/layout.json, servo.bam): voltage control through
the firmware P gain, motor back-EMF, and load-dependent friction. On top of the identified servo: the supply varies
like a 2S battery and sags under load, commands arrive 10-40 ms late (bus and firmware), and the torque is capped
at the stall torque on the servo label, below what the identified motor constants would reach.
"""

import json
import pathlib

from isaaclab_newton.sim.schemas import NewtonArticulationCfg

import isaaclab.sim as sim_utils
from isaaclab.actuators import BamActuatorCfg, BamMotorCfg
from isaaclab.assets import ArticulationCfg

REPO = pathlib.Path(__file__).resolve().parents[2]
_SERVO_DATA = json.loads((REPO / "cad" / "sts3215" / "layout.json").read_text())["servo"]
SERVO = _SERVO_DATA["variants"]["19kg"]
BAM = _SERVO_DATA["bam"]

STAND_HEIGHT = 0.168
"""Trunk frame height [m] in the standing pose (build_mjcf.py prints it: 165.8 mm, plus a small drop)."""

SOLE_TO_ANKLE = 0.0356
"""Ankle frame height above the sole [m] with the foot flat (ankle axis 50.1 mm, sole bottom 14.5 mm)."""

STANDING_POSE = {
    ".*hip_yaw": 0.0,
    "left_hip_roll": -0.0873,
    "right_hip_roll": 0.0873,
    "left_hip_pitch": -0.4579,
    "right_hip_pitch": 0.4579,
    "left_knee": -0.0049,
    "right_knee": 0.0049,
    "left_ankle": 0.4530,
    "right_ankle": -0.4530,
    "neck_pitch": 0.3491,
    "head_pitch": 0.3491,
    "head_yaw": 0.0,
    "head_roll": 0.0,
}

STS3215_CFG = ArticulationCfg(
    spawn=sim_utils.UsdFileCfg(
        usd_path=str(REPO / "sim" / "sts3215" / "usd" / "robot_walk" / "robot_walk.usda"),
        activate_contact_sensors=True,
        articulation_props=NewtonArticulationCfg(self_collision_enabled=True),
    ),
    init_state=ArticulationCfg.InitialStateCfg(
        pos=(0.0, 0.0, STAND_HEIGHT), joint_pos={**STANDING_POSE, "passive_.*": 0.0}, joint_vel={".*": 0.0}
    ),
    soft_joint_pos_limit_factor=0.9,
    actuators={
        "servos": BamActuatorCfg(
            joint_names_expr=["^(?!passive_).*"],
            motor=BamMotorCfg(
                model=BAM["model"],
                kt=BAM["kt"],
                resistance=BAM["resistance"],
                error_gain=BAM["error_gain"],
                max_pwm=BAM["max_pwm"],
                max_current=0.0,
                **{k: BAM[k] for k in (
                    "friction_base", "friction_viscous", "friction_stribeck", "dtheta_stribeck", "alpha",
                    "load_friction_motor", "load_friction_external", "load_friction_motor_stribeck",
                    "load_friction_external_stribeck", "load_friction_motor_quad", "load_friction_external_quad")},
            ),
            kp_fw=BAM["kp_fw"],
            vin=BAM["vin"],
            vin_range=(6.6, 8.4),  # 2S LiPo, empty to full
            vin_drop_gain_range=(0.0, 0.2),
            vin_min=6.0,
            min_delay=2,  # physics steps of 5 ms
            max_delay=8,
            actuator_effort_limit=SERVO["stall_nm"],
            backlash_joint_template="passive_{}_backlash",
        ),
    },
)
"""STS3215 Microduck (ST-3215-C001, 19.5 kg cm at 7.4 V) with BAM servos and gearbox play."""
