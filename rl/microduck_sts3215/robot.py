"""The STS3215 Microduck as an Isaac Lab articulation.

The model is sim/sts3215/robot_walk.xml (generated by cad/sts3215/build_mjcf.py: soles-only collisions, no
MuJoCo actuators), converted to USD by rl/convert_usd.py. Each servo is a DC motor:
the torque is clipped to the line from the stall torque at zero speed to zero at the no-load speed, with the
values from the servo label in cad/sts3215/layout.json.
"""

import json
import pathlib

from isaaclab_newton.sim.schemas import NewtonArticulationCfg

import isaaclab.sim as sim_utils
from isaaclab.actuators import DCMotorCfg
from isaaclab.assets import ArticulationCfg

REPO = pathlib.Path(__file__).resolve().parents[2]
SERVO = json.loads((REPO / "cad" / "sts3215" / "layout.json").read_text())["servo"]["variants"]["19kg"]

STAND_HEIGHT = 0.168
"""Trunk frame height [m] in the standing pose (build_mjcf.py prints it: 165.8 mm, plus a small drop)."""

SOLE_TO_ANKLE = 0.0356
"""Ankle frame height above the sole [m] with the foot flat (ankle axis 50.1 mm, sole bottom 14.5 mm)."""

STANDING_POSE = {
    ".*hip_yaw": 0.0,
    "left_hip_roll": -0.0873,
    "right_hip_roll": 0.0873,
    "left_hip_pitch": -0.4579,
    "right_hip_pitch": 0.4579,
    "left_knee": -0.0049,
    "right_knee": 0.0049,
    "left_ankle": 0.4530,
    "right_ankle": -0.4530,
    "neck_pitch": 0.3491,
    "head_pitch": 0.3491,
    "head_yaw": 0.0,
    "head_roll": 0.0,
}

STS3215_CFG = ArticulationCfg(
    spawn=sim_utils.UsdFileCfg(
        usd_path=str(REPO / "sim" / "sts3215" / "usd" / "robot_walk" / "robot_walk.usda"),
        activate_contact_sensors=True,
        articulation_props=NewtonArticulationCfg(self_collision_enabled=True),
    ),
    init_state=ArticulationCfg.InitialStateCfg(
        pos=(0.0, 0.0, STAND_HEIGHT), joint_pos=STANDING_POSE, joint_vel={".*": 0.0}
    ),
    soft_joint_pos_limit_factor=0.9,
    actuators={
        "servos": DCMotorCfg(
            joint_names_expr=[".*"],
            saturation_effort=SERVO["stall_nm"],
            actuator_effort_limit=SERVO["stall_nm"],
            actuator_velocity_limit=SERVO["no_load_rad_s"],
            # starting values, to identify on a real servo (step response)
            stiffness=18.0,
            damping=0.6,
            armature=0.02,
            friction=0.05,
        ),
    },
)
"""STS3215 Microduck (ST-3215-C001, 19.5 kg cm at 7.4 V) with DC-motor servos."""
